def simulate_bifrost_completion(messages: List[Dict[str, str]], model: str) -> MockCompletionResponse:
    """
    Simulates a Bifrost Gateway completion when Bifrost is not configured or offline.
    Identifies task intent from the prompt and returns precise, syntactically correct code.
    Calculates realistic token count based on input characters / 4.
    """
    combined_prompt = " ".join([m.get("content", "") for m in messages]).lower()

    # Identify matching demo task
    selected_key = "calculator"
    if "student" in combined_prompt:
        selected_key = "student_management"
    elif "prime" in combined_prompt:
        selected_key = "prime_checker"
    elif "sort" in combined_prompt or "quicksort" in combined_prompt:
        selected_key = "sorting_algorithm"
    elif "inventory" in combined_prompt:
        selected_key = "inventory_management"
    elif "fix" in combined_prompt or "debug" in combined_prompt or "error" in combined_prompt:
        # Check if this is a debug call
        selected_key = "calculator"

    task_data = DEMO_TASK_SOLUTIONS[selected_key]

    # Check if this is an error correction call
    is_repair_request = (
        "surgical debugger" in combined_prompt
        or "fix the targeted error" in combined_prompt
        or ("current code:" in combined_prompt and ("error:" in combined_prompt or "traceback" in combined_prompt))
    )
    if is_repair_request:
        content = f"""```python
# Fixed targeted function via CodeLite AI Targeted Debugger
{task_data['code']}
```"""
    elif "generate unit test" in combined_prompt or "test suite" in combined_prompt or "unittest" in combined_prompt:
        content = f"""```python
{task_data['tests']}
```"""
    elif "analyze" in combined_prompt or "task analyzer" in combined_prompt:
        content = f"""{{
  "task_name": "{selected_key.replace('_', ' ').title()}",
  "language": "python",
  "complexity": "moderate",
  "inputs": "Task parameters and data structures",
  "outputs": "Clean class/module with deterministic execution",
  "edge_cases": ["zero values", "empty inputs", "invalid types"]
}}"""
    else:
        # Standard code generation
        content = f"""```python
{task_data['code']}
```

```python
# Tests
{task_data['tests']}
```"""

    # Realistic token estimation: 1 token ~ 3.8 - 4.2 characters
    prompt_len = sum(len(m.get("content", "")) for m in messages)
    prompt_tokens = max(18, int(prompt_len / 4.0))
    completion_tokens = max(25, int(len(content) / 4.0))

    return MockCompletionResponse(
        content=content,
        prompt_tokens=prompt_tokens,
        completion_tokens=completion_tokens,
        model=model,
    )
