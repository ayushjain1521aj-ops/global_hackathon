class MockCompletionChoice:
    def __init__(self, content: str):
        self.message = type("Msg", (), {"content": content, "role": "assistant"})()
        self.finish_reason = "stop"


class MockUsage:
    def __init__(self, prompt_tokens: int, completion_tokens: int):
        self.prompt_tokens = prompt_tokens
        self.completion_tokens = completion_tokens
        self.total_tokens = prompt_tokens + completion_tokens

    def dict(self):
        return {
            "prompt_tokens": self.prompt_tokens,
            "completion_tokens": self.completion_tokens,
            "total_tokens": self.total_tokens,
        }


class MockCompletionResponse:
    def __init__(self, content: str, prompt_tokens: int, completion_tokens: int, model: str):
        self.id = f"simulated-bifrost-{uuid.uuid4().hex[:10]}"
        self.choices = [MockCompletionChoice(content)]
        self.usage = MockUsage(prompt_tokens, completion_tokens)
        self.model = f"[SIMULATED] {model}"
        self.created = int(time.time())
        self.is_simulated = True


